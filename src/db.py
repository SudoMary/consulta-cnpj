"""Conexão com o banco e aplicação do schema.

O mesmo SQL roda em dois bancos: SQLite no desenvolvimento e nos testes, sem
conexão, e PostgreSQL (Supabase) em produção, porque a hospedagem grátis apaga
os arquivos locais. O SQLAlchemy cuida só da conexão, dos parâmetros e das
transações; o SQL continua escrito à mão em `repo.py`.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from sqlalchemy import Engine, create_engine, event

# Localiza `schema.sql` na raiz do projeto, independente do cwd em que o
# processo foi iniciado.
_SCHEMA_PATH = Path(__file__).resolve().parent.parent / "schema.sql"

# A única diferença de DDL entre os dois bancos: como o `id` é gerado.
_CHAVE_SUBSTITUTA = {
    "sqlite": "INTEGER PRIMARY KEY",
    "postgresql": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
}


def criar_motor(url: str) -> Engine:
    """Abre o banco da URL e aplica o schema.

    Idempotente: o schema usa ``IF NOT EXISTS``, então rodar duas vezes no
    mesmo banco não quebra. O chamador encerra com ``motor.dispose()``.
    """
    motor = create_engine(url)
    if motor.dialect.name == "sqlite":
        event.listen(motor, "connect", _ligar_chaves_estrangeiras)
    _aplicar_schema(motor)
    return motor


def _ligar_chaves_estrangeiras(conexao: Any, _registro: Any) -> None:
    # O SQLite ignora FK por padrão e precisa disto em toda conexão; sem
    # isto, REFERENCES é decoração. O PostgreSQL já as respeita.
    conexao.execute("PRAGMA foreign_keys = ON")


def _aplicar_schema(motor: Engine) -> None:
    # UTF-8 explícito: o schema tem comentários acentuados e o padrão no
    # Windows é cp1252.
    schema = _SCHEMA_PATH.read_text(encoding="utf-8").replace(
        "CHAVE_SUBSTITUTA", _CHAVE_SUBSTITUTA[motor.dialect.name]
    )
    if motor.dialect.name == "sqlite":
        # O driver do SQLite só executa vários comandos de uma vez por aqui.
        bruta = motor.raw_connection()
        try:
            bruta.driver_connection.executescript(schema)
        finally:
            bruta.close()
    else:
        with motor.begin() as con:
            con.exec_driver_sql(schema)
